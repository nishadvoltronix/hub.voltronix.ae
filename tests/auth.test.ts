test("CSRF is session-bound, rotatable and invalid after logout", async (t) => {
  const db = fixtureDatabase(t);
  const auth = createAuthService(db);
  const one = await auth.login(email, fixture.password, "web");
  const two = await auth.login(email, fixture.password, "web");
  assert.equal(auth.verifySessionCsrf(one.sessionToken, one.csrfToken), true);
  assert.equal(auth.verifySessionCsrf(one.sessionToken, two.csrfToken), false);
  assert.equal(auth.verifySessionCsrf(one.sessionToken, "wrong"), false);
  const replacement = randomBytes(32).toString("base64url");
  assert.equal(auth.setSessionCsrf(one.sessionToken, replacement), true);
  assert.equal(auth.verifySessionCsrf(one.sessionToken, one.csrfToken), false);
  assert.equal(auth.verifySessionCsrf(one.sessionToken, replacement), true);
  auth.logout(one.sessionToken);
  assert.equal(auth.verifySessionCsrf(one.sessionToken, replacement), false);
  assert.equal(auth.setSessionCsrf(one.sessionToken, replacement), false);
});

