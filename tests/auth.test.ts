test("explicit development provisioning is transactional, bounded, and never overwrites", async (t) => {
  const db = fixtureDatabase(t);
  const input = { environment: "development", email: "created@isolated.example", name: "Explicit synthetic test",
    password: "Development-fixture-created-123!", permissions: ["leads.view"] };
  const id = await createDevelopmentUser(db, input);
  assert.ok(id);
  const session = await createAuthService(db).login(input.email, input.password, "web");
  assert.equal(session.user.externalUserId, null);
  assert.deepEqual(session.user.permissions, ["leads.view"]);
  await assert.rejects(createDevelopmentUser(db, input), DevelopmentUserError);
  await assert.rejects(createDevelopmentUser(db, { ...input, environment: "production" }), DevelopmentUserError);
  await assert.rejects(createDevelopmentUser(db, { ...input, email: "weak@isolated.example", password: "short" }), DevelopmentUserError);
  await assert.rejects(createDevelopmentUser(db, { ...input, email: "long@isolated.example", password: "é".repeat(37) }), DevelopmentUserError);
  await assert.rejects(createDevelopmentUser(db, { ...input, email: "short-unicode@isolated.example", password: "🔐".repeat(6) }), DevelopmentUserError);
  await assert.rejects(createDevelopmentUser(db, { ...input, permissions: ["admin.everything"] }), DevelopmentUserError);
  assert.equal((db.prepare("SELECT COUNT(*) AS count FROM users").get() as { count: number }).count, 3);
});

test("development grants and account creation roll back together on a database failure", async (t) => {
  const db = fixtureDatabase(t);
  db.exec("CREATE TRIGGER fail_test_grant BEFORE INSERT ON admin_user_permissions BEGIN SELECT RAISE(ABORT, 'isolated test'); END;");
  await assert.rejects(createDevelopmentUser(db, { environment: "development", email: "rollback@isolated.example",
    name: "Synthetic rollback", password: "Rollback-test-password-123", permissions: ["leads.view"] }), DevelopmentUserError);
  assert.equal(db.prepare("SELECT 1 FROM users WHERE email='rollback@isolated.example'").get(), undefined);
  assert.equal(db.prepare('SELECT 1 FROM permissions WHERE "key" = ?').get("leads.view"), undefined);
});
