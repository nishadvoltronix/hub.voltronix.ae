test("login reservations are atomic before async bcrypt and expire after fifteen minutes", async (t) => {
  const db = fixtureDatabase(t);
  let timestamp = 10_000;
  const auth = createAuthService(db, { now: () => timestamp });
  const results = await Promise.allSettled(Array.from({ length: 6 }, () => auth.login(email, fixture.password, "web")));
  assert.equal(results.filter((result) => result.status === "fulfilled").length, 5);
  const failure = results.find((result) => result.status === "rejected");
  assert.ok(failure?.status === "rejected" && isStatus(429)(failure.reason));
  timestamp += LOGIN_WINDOW_MS;
  assert.ok(await auth.login(email, fixture.password, "web"));
});

test("throttle buckets persist across SQLite reopen and global limit stops new account buckets", async (t) => {
  const directory = mkdtempSync(join(tmpdir(), "crm-auth-isolated-"));
  const filename = join(directory, "fixture.sqlite");
  let db = new Database(filename);
  t.after(() => { if (db.open) db.close(); rmSync(directory, { recursive: true, force: true }); });
  configureDatabase(db);
  migrateDatabase(db);
  addUser(db, 1, email, externalId);
  let auth = createAuthService(db);
  for (let count = 0; count < 5; count++) await auth.login(email, fixture.password, "web");
  db.close();
  db = new Database(filename);
  configureDatabase(db);
  auth = createAuthService(db);
  await assert.rejects(auth.login(email, fixture.password, "web"), isStatus(429));
  db.prepare("UPDATE crm_login_attempts SET attempts=100 WHERE bucket LIKE 'client:%'").run();
  await assert.rejects(auth.login("new-account@isolated.example", fixture.password, "web"), isStatus(429));
  assert.equal((db.prepare("SELECT COUNT(*) AS count FROM crm_login_attempts").get() as { count: number }).count, 2);
});

