// Exclusively synthetic fixtures generated by the local PHP 8.2.34 password APIs.
const fixtureDocument = JSON.parse(readFileSync(new URL("./fixtures/php-bcrypt.json", import.meta.url), "utf8")) as {
  cases: { name: string; password: string; hash: string; phpVerified: boolean }[];
};
const fixture = fixtureDocument.cases[0]!;
const email = "one@isolated.example";
const externalId = "90071992547409931";
function fixtureDatabase(t: TestContext) {
  const db = new Database(":memory:");
  configureDatabase(db);
  migrateDatabase(db);
  t.after(() => db.close());
  addUser(db, 1, email, externalId);
  addUser(db, 2, "two@isolated.example", "external-two");
  return db;
}
function addUser(db: Database.Database, id: number | bigint, accountEmail: string, external: string | null) {
  db.prepare("INSERT INTO users(id,user_id,username,email,password,status) VALUES (?,?, 'Synthetic test user',?,?,'active')")
    .run(id, external, accountEmail, fixture.hash);
}
function grant(db: Database.Database, id: number, key: string) {
  db.prepare('INSERT INTO permissions("key",label) VALUES (?,?) ON CONFLICT("key") DO NOTHING').run(key, key);
  db.prepare('INSERT INTO admin_user_permissions(admin_user_id,permission_id) SELECT ?,id FROM permissions WHERE "key"=?').run(id, key);
}
function task(db: Database.Database, id: number, assignedTo: string | null) {
  db.prepare("INSERT INTO tasks(id,assigned_to,deal_name,status) VALUES (?,?,'Synthetic isolated task','Qualification')").run(id, assignedTo);
}
function isStatus(status: number) { return (error: unknown) => error instanceof AuthError && error.status === status; }

test("PHP-generated bcrypt $2y$ fixtures match UTF-8, whitespace and legacy 72-byte truncation", async () => {
  for (const value of fixtureDocument.cases) {
    assert.equal(value.phpVerified, true);
    assert.ok(value.hash.startsWith("$2y$"));
    assert.equal(await compare(value.password, value.hash), true, value.name);
    assert.equal(await compare("incorrect-test-password", value.hash), false, value.name);
    if (value.name.includes("truncation")) {
      const prefix = Buffer.from(value.password).subarray(0, 72).toString("utf8");
      assert.equal(await compare(prefix + "-different-suffix", value.hash), true);
    }
  }
});

test("login preserves PHP hashes and string identity domains and stores only token digests", async (t) => {
  const db = fixtureDatabase(t);
  grant(db, 1, "leads.view");
  const auth = createAuthService(db);
  const session = await auth.login(email.toUpperCase(), fixture.password, "web");
  assert.equal(session.user.localUserId, "1");
  assert.equal(session.user.externalUserId, externalId);
  assert.deepEqual(session.user.permissions, ["leads.view"]);
  assert.equal(session.sessionToken.length, 43);
  assert.equal(session.csrfToken.length, 43);
  const stored = db.prepare("SELECT * FROM crm_sessions").get() as Record<string, unknown>;
  assert.equal(stored.token_hash === session.sessionToken, false);
  assert.equal(stored.csrf_hash === session.csrfToken, false);
  assert.equal((db.prepare("SELECT password FROM users WHERE id=1").get() as { password: string }).password, fixture.hash);
  assert.equal(auth.authenticate(session.sessionToken)?.localUserId, "1");
  assert.equal("password" in session.user, false);
});

test("wrong password, inactive, absent and unsupported hash accounts fail generically", async (t) => {
  const db = fixtureDatabase(t);
  const auth = createAuthService(db);
  await assert.rejects(auth.login(email, "wrong password", "web"), isStatus(401));
  await assert.rejects(auth.login("missing@isolated.example", fixture.password, "web"), isStatus(401));
  db.prepare("UPDATE users SET status='inactive' WHERE id=1").run();
  await assert.rejects(auth.login(email, fixture.password, "web"), isStatus(401));
  db.prepare("UPDATE users SET status='active',password='unsupported-test-only' WHERE id=1").run();
  await assert.rejects(auth.login(email, fixture.password, "web"), isStatus(401));
  assert.equal((db.prepare("SELECT COUNT(*) AS total FROM crm_sessions").get() as { total: number }).total, 0);
});

test("input injection and arbitrary session tokens never authenticate or expose tasks", async (t) => {
  const db = fixtureDatabase(t);
  const auth = createAuthService(db);
  await assert.rejects(auth.login("' OR 1=1 --", fixture.password, "web"), isStatus(401));
  await assert.rejects(auth.login({ email }, fixture.password, "web"), isStatus(401));
  assert.equal(auth.authenticate("' OR 1=1 --"), null);
  assert.equal(auth.authenticate(randomBytes(32).toString("base64url")), null);
  const session = await auth.login(email, fixture.password, "web");
  grant(db, 1, "leads.view");
  task(db, 1, externalId);
  assert.throws(() => auth.getAuthorizedTask(session.sessionToken, "1 OR 1=1"), isStatus(404));
  assert.throws(() => auth.getAuthorizedTask(null, "1"), isStatus(401));
});

test("active status and revoked grants are reloaded and role never supplies permissions", async (t) => {
  const db = fixtureDatabase(t);
  grant(db, 1, "leads.view");
  task(db, 1, "external-two");
  const auth = createAuthService(db);
  const session = await auth.login(email, fixture.password, "web");
  assert.equal(auth.getAuthorizedTask(session.sessionToken, "1").id, "1");
  db.prepare("DELETE FROM admin_user_permissions WHERE admin_user_id=1").run();
  db.prepare("UPDATE users SET role='admin',quote_access=1 WHERE id=1").run();
  assert.deepEqual(auth.authenticate(session.sessionToken)?.permissions, []);
  assert.throws(() => requirePermission(auth.authenticate(session.sessionToken)!, "users.write"), isStatus(403));
  assert.throws(() => auth.getAuthorizedTask(session.sessionToken, "1"), isStatus(404));
  db.prepare("UPDATE users SET status='inactive' WHERE id=1").run();
  assert.equal(auth.authenticate(session.sessionToken), null);
  db.prepare("UPDATE users SET status='active' WHERE id=1").run();
  assert.equal(auth.authenticate(session.sessionToken), null);
});

test("sessions expire absolutely, revoke on logout and invalidate after password changes", async (t) => {
  const db = fixtureDatabase(t);
  let timestamp = 1_000_000;
  const auth = createAuthService(db, { now: () => timestamp });
  const first = await auth.login(email, fixture.password, "web");
  timestamp += SESSION_LIFETIME_MS - 1;
  assert.ok(auth.authenticate(first.sessionToken));
  timestamp++;
  assert.equal(auth.authenticate(first.sessionToken), null);
  const second = await auth.login(email, fixture.password, "web");
  assert.notEqual(second.sessionToken, first.sessionToken);
  auth.logout(second.sessionToken);
  assert.equal(auth.authenticate(second.sessionToken), null);
  const third = await auth.login(email, fixture.password, "web");
  db.prepare("UPDATE users SET password=? WHERE id=1").run(fixtureDocument.cases[1]!.hash);
  assert.equal(auth.authenticate(third.sessionToken), null);
});

